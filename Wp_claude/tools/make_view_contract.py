"""Generate Wp_claude/ARCH/view_contract.md (package 23 C): for every panel of the registry, the view, its parameters,
the fields it returns (names and types, read from a real sample character), the commands the panel calls (parameters
and refusal reasons) and the topics it refreshes on. Deterministic; a test checks the file is up to date.
The UI work reads this file instead of the code. Usage: python Wp_claude/tools/make_view_contract.py
"""
import ast
import dataclasses
import inspect
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "Wp_claude", "tests", "perf"))
import heavy  # noqa: E402

from wp.app import session as sm  # noqa: E402
from wp.app import views as vw  # noqa: E402
from wp.commands import REGISTRY  # noqa: E402
from wp.panels import registry  # noqa: E402
from wp.rules_data import rules as rd  # noqa: E402

OUT = os.path.join(ROOT, "Wp_claude", "ARCH", "view_contract.md")


def _type(v):
    if dataclasses.is_dataclass(v) and not isinstance(v, type):
        return type(v).__name__
    if isinstance(v, (tuple, list)):
        inner = sorted({_type(x) for x in v})
        return "tuple[%s]" % ("|".join(inner) if inner else "")
    if isinstance(v, dict):
        return "map"
    return type(v).__name__


def _fields(v, depth=0):
    """Lines "name: type" for a dataclass / dict (one level deeper for nested ones)."""
    pad = "  " * depth
    out = []
    if dataclasses.is_dataclass(v) and not isinstance(v, type):
        items = [(f.name, getattr(v, f.name)) for f in dataclasses.fields(v)]
    elif isinstance(v, dict):
        items = sorted(((str(k), x) for k, x in v.items()), key=lambda kv: kv[0])
    elif isinstance(v, (tuple, list)):
        sample = next((x for x in v if dataclasses.is_dataclass(x) or isinstance(x, dict)), None)
        out.append("%s- (each item: %s)" % (pad, _type(v)))
        if sample is not None and depth < 1:
            out += _fields(sample, depth + 1)
        return out
    else:
        return ["%s- %s" % (pad, _type(v))]
    if isinstance(v, dict) and len(items) > 25:           # a map keyed by ids (settings, groups): show the value type
        return ["%s- map of %d entries: value %s" % (pad, len(items), sorted({_type(x) for _, x in items}))]
    for name, x in items:
        out.append("%s- `%s`: %s" % (pad, name, _type(x)))
        if depth < 1 and (dataclasses.is_dataclass(x) and not isinstance(x, type) or
                          (isinstance(x, dict) and 0 < len(x) <= 25)):
            out += _fields(x, depth + 1)
    return out


def _reasons_by_function():
    out = {}
    for name, fn in REGISTRY.items():
        src = inspect.getsource(fn)
        tree = ast.parse(src.replace("\n    ", "\n") if src.startswith("    ") else src)
        found = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and getattr(node.func, "id", None) == "CommandError" and len(node.args) > 1 \
                    and isinstance(node.args[1], ast.Constant):
                found.add(node.args[1].value)
        out[name] = sorted(found)
    return out


def _signature(fn):
    params = list(inspect.signature(fn).parameters.values())[1:]
    return ", ".join(p.name if p.default is inspect.Parameter.empty else "%s=%r" % (p.name, p.default)
                     for p in params if p.kind not in (p.VAR_KEYWORD, p.VAR_POSITIONAL)) + \
        (", **fields" if any(p.kind == p.VAR_KEYWORD for p in params) else "")


def build_text():
    ch = heavy.heavy()
    reasons = _reasons_by_function()
    every = sorted(c for c, t in sm.TOPICS.items() if "all" in t)
    lines = ["# View contract (generated by Wp_claude/tools/make_view_contract.py; do not edit by hand)", "",
             "The UI talks only to `wp.app.session.Session` (D25): `session.view(panel id, **params)` gives the data of a "
             "panel, `session.dispatch(command, **params)` changes the character and returns the topics (panel ids) to "
             "refresh. Fields below are read from a sample character (tests/perf/heavy.py).", "",
             "Commands that refresh EVERY panel: " + ", ".join("`%s`" % c for c in every), ""]
    for pid in sorted(registry.PANELS):
        p = registry.PANELS[pid]
        fn = vw.VIEWS[pid]
        with rd.using(ch):
            sample = fn(ch, None)
        cmds = sorted(c for c, t in sm.TOPICS.items() if pid in t)
        lines += ["## %s" % pid, "",
                  "- view: `session.view(%r%s)`" % (pid, "".join(", %s=..." % x for x in vw.PARAMS.get(pid, ()))),
                  "- modes: %s; described in the docs: %s" % (", ".join(p["modes"]), "yes" if p["described"] else "no"),
                  "- refreshes on its topic `%s` and on the commands that refresh every panel" % pid,
                  "- returns: %s" % _type(sample)]
        lines += _fields(sample)
        lines += ["- commands:"] + ["  - `%s(%s)`%s" % (c, _signature(REGISTRY[c]),
                                                        (" reasons: " + ", ".join(reasons[c])) if reasons[c] else "")
                                    for c in cmds] + [""]
    return "\n".join(lines) + "\n"


def main():
    text = build_text()
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("%s: %d lines, %d bytes" % (os.path.relpath(OUT, ROOT), text.count("\n"), len(text.encode("utf-8"))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
