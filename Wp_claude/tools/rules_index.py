"""Regenerate the "Sections" block of Wp_claude/RULES/index.md.

For every RULES/*.md file (except index.md) the block gets two lines:
    - `file.md` (N lines): what it covers (taken from the "| File | Covers |" table of index.md)
      sections: heading (line) | heading (line) | ...
Only the text between the START and END markers is replaced; the rest of index.md is not touched.
Line endings of index.md are kept. Run after any RULES file gains, loses or renames a "## " heading.
Usage: python Wp_claude/tools/rules_index.py [--check]   (--check: exit 1 if the block is out of date)
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RULES = os.path.join(os.path.dirname(HERE), "RULES")
INDEX = os.path.join(RULES, "index.md")
START = "<!-- sections:start (generated by Wp_claude/tools/rules_index.py, do not edit by hand) -->"
END = "<!-- sections:end -->"


def covers(index_text):
    out = {}
    for line in index_text.split("\n"):
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 2 and cells[0].endswith(".md"):
            out[cells[0]] = cells[1]
    return out


def headings(text):
    return ["%s (%d)" % (ln[3:].strip(), i) for i, ln in enumerate(text.split("\n"), 1) if ln.startswith("## ")]


def block(index_text):
    cov = covers(index_text)
    lines = [START, "## Sections", "Search a file by its heading (`grep -n \"^## \"`), then read only that section.", ""]
    for path in sorted(glob.glob(os.path.join(RULES, "*.md"))):
        name = os.path.basename(path)
        if name == "index.md":
            continue
        text = open(path, "rb").read().decode("utf-8").replace("\r\n", "\n")
        n = text.count("\n") + (0 if text.endswith("\n") else 1)
        lines.append("- `%s` (%d lines): %s" % (name, n, cov.get(name, "(not in the table above)")))
        lines.append("  sections: " + (" | ".join(headings(text)) or "(no ## headings)"))
    lines.append(END)
    return "\n".join(lines)


def rebuild(index_text):
    if START in index_text and END in index_text:
        head, rest = index_text.split(START, 1)
        tail = rest.split(END, 1)[1]
        return head + block(index_text) + tail
    return index_text.rstrip("\n") + "\n\n" + block(index_text) + "\n"


def main(argv):
    raw = open(INDEX, "rb").read()
    nl = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    new = rebuild(text)
    if "--check" in argv:
        print("index.md sections: " + ("up to date" if new == text else "OUT OF DATE"))
        return 0 if new == text else 1
    open(INDEX, "wb").write(new.replace("\n", nl).encode("utf-8"))
    print("index.md sections rebuilt")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
